/**
 * Paths, staging, the generated dotenv file, and the loopback probes.
 *
 * Everything here is deliberately free of Cordis and of the supervisor's state:
 * a path is a path, a copy is a copy, a probe either answers or it does not.
 * `test/check.mjs` exercises these helpers directly, which is why they take
 * explicit directories instead of reading globals.
 */
import fs from 'node:fs'
import fsp from 'node:fs/promises'
import net from 'node:net'
import os from 'node:os'
import path from 'node:path'
import crypto from 'node:crypto'
import { fileURLToPath } from 'node:url'

import {
  ENV_FILE_NAME,
  EXE_BASENAME,
  LOG_FILE_NAME,
  RUNTIME_DIR,
  SECRET_ENV_KEYS,
  SECRET_LENGTH,
  STATE_FILE_NAME
} from './protocol.js'

/** The package root: `src/` is one level down, so this stays correct when packed. */
export function packageRoot() {
  return path.resolve(fileURLToPath(new URL('..', import.meta.url)))
}

/** `$DSH_HOME`, falling back to the documented `~/.dsh`. */
export function dshHome(env = process.env) {
  const value = env?.DSH_HOME
  if (typeof value === 'string' && value.trim() !== '') return path.resolve(value.trim())
  return path.join(os.homedir(), '.dsh')
}

/**
 * The plugin's private directory under the DSH home.
 *
 * `config.dataDir` overrides it wholesale, so a user who wants the database on
 * another drive does not have to move anything afterwards.
 */
export function pluginHome(config = {}, env = process.env) {
  const custom = typeof config?.dataDir === 'string' ? config.dataDir.trim() : ''
  if (custom !== '') return path.resolve(custom)
  return path.join(dshHome(env), RUNTIME_DIR)
}

/** The platform asset directory this package ships (`assets/<platform>-<arch>`). */
export function assetRoot(root = packageRoot()) {
  return path.join(root, 'assets', `${process.platform}-${process.arch}`)
}

/** Every bundled path the supervisor needs, named once. */
export function assetPaths(root = packageRoot()) {
  const dir = assetRoot(root)
  return {
    dir,
    exe: path.join(dir, EXE_BASENAME),
    web: path.join(dir, 'web'),
    config: path.join(dir, 'config'),
    migrations: path.join(dir, 'migrations'),
    sqliteMigrations: path.join(dir, 'migrations', 'sqlite')
  }
}

/**
 * Which bundled pieces are absent.
 *
 * A missing executable or `web/` cannot be worked around, so the tool reports the
 * exact path instead of a spawn error from `ENOENT` naming only the binary.
 */
export function missingAssets(paths) {
  const wanted = [
    ['executable', paths.exe],
    ['web assets', paths.web],
    ['config directory', paths.config],
    ['migrations', paths.sqliteMigrations]
  ]
  const missing = []
  for (const [label, target] of wanted) {
    if (!fs.existsSync(target)) missing.push(`${label}: ${target}`)
  }
  return missing
}

/** Forward slashes, because the generated dotenv is read by a Go program on Windows. */
export function toPosix(value) {
  return String(value).split('\\').join('/')
}

/** "32 characters" is a byte count for these keys: readable ASCII, no quoting. */
const SECRET_ALPHABET = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'

export function randomSecret(length = SECRET_LENGTH) {
  const bytes = crypto.randomBytes(length)
  let text = ''
  for (const byte of bytes) text += SECRET_ALPHABET[byte % SECRET_ALPHABET.length]
  return text
}

/**
 * The dotenv body for one installation.
 *
 * `ENV_FILE` makes this the only file the child reads (the binary would otherwise
 * look beside its executable, which is inside `node_modules`), and process-level
 * variables still win over it, which is how the port is pinned on every start.
 */
export function envFileText({ dataDir }) {
  const data = toPosix(dataDir)
  return [
    '# Generated by dsh-weknora-win. Edit values, keep the keys: the child reads this',
    '# file through ENV_FILE, and missing core keys make it exit at startup.',
    '',
    'DB_DRIVER=sqlite',
    `DB_PATH=${data}/weknora.db`,
    'RETRIEVE_DRIVER=sqlite',
    'STORAGE_TYPE=local',
    `LOCAL_STORAGE_BASE_DIR=${data}/files`,
    'STREAM_MANAGER_TYPE=memory',
    'OLLAMA_BASE_URL=http://127.0.0.1:11434',
    `SYSTEM_AES_KEY=${randomSecret()}`,
    `JWT_SECRET=${randomSecret(48)}`,
    'NEO4J_ENABLE=false',
    'WEKNORA_SANDBOX_MODE=disabled',
    'ENABLE_GRAPH_RAG=false',
    'DISABLE_REGISTRATION=false',
    'CONCURRENCY_POOL_SIZE=3',
    'GIN_MODE=release',
    'LOG_LEVEL=info',
    ''
  ].join('\n')
}

/** The `KEY=value` pairs of a dotenv body, ignoring comments and blank lines. */
export function parseEnv(text) {
  const values = new Map()
  for (const line of String(text).split(/\r?\n/)) {
    const match = /^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line)
    if (match !== null) values.set(match[1], match[2])
  }
  return values
}

/**
 * Create the dotenv file on first use, and repair it afterwards.
 *
 * Repair means exactly two things: a secret that is missing or empty is generated
 * (a blank key means plaintext credential storage and degraded signing), and a
 * core key the user deleted is re-added with its default. Every value the user
 * changed is left alone.
 */
export async function ensureEnvFile(envPath, { dataDir, log = () => {} }) {
  let text = ''
  try {
    text = await fsp.readFile(envPath, 'utf8')
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error
    await fsp.mkdir(path.dirname(envPath), { recursive: true })
    await fsp.writeFile(envPath, envFileText({ dataDir }), { encoding: 'utf8', mode: 0o600 })
    log(`created ${envPath}`)
    return { path: envPath, created: true }
  }
  const values = parseEnv(text)
  const defaults = parseEnv(envFileText({ dataDir }))
  const additions = []
  for (const [key, value] of defaults) {
    const current = values.get(key)
    if (key.startsWith('#')) continue
    if (SECRET_ENV_KEYS.includes(key)) {
      if (current === undefined || current.trim() === '') additions.push(`${key}=${value}`)
      continue
    }
    if (current === undefined) additions.push(`${key}=${value}`)
  }
  if (additions.length === 0) return { path: envPath, created: false }
  const body = text.endsWith('\n') ? text : `${text}\n`
  await fsp.writeFile(envPath, `${body}${additions.join('\n')}\n`, { encoding: 'utf8', mode: 0o600 })
  log(`repaired ${envPath}: ${additions.length} key(s)`)
  return { path: envPath, created: false, repaired: true }
}

/** Every file under `source`, relative, POSIX-shaped. */
async function walk(source, prefix = '') {
  const entries = await fsp.readdir(source, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const relative = prefix === '' ? entry.name : `${prefix}/${entry.name}`
    if (entry.isDirectory()) files.push(...(await walk(path.join(source, entry.name), relative)))
    else if (entry.isFile()) files.push(relative)
  }
  return files
}

/**
 * Copy a tree, adding only what is absent.
 *
 * Used for `config/`: `config.yaml` and the prompt templates are shipped defaults,
 * but a user may edit them, so an upgrade must not overwrite an existing file.
 */
export async function copyTreeMissing(source, target) {
  if (!fs.existsSync(source)) return 0
  let copied = 0
  for (const relative of await walk(source)) {
    const from = path.join(source, ...relative.split('/'))
    const to = path.join(target, ...relative.split('/'))
    if (fs.existsSync(to)) continue
    await fsp.mkdir(path.dirname(to), { recursive: true })
    await fsp.copyFile(from, to)
    copied += 1
  }
  return copied
}

/**
 * Copy a tree, replacing files that differ in size.
 *
 * Used for `migrations/sqlite/`: these are versioned SQL scripts, never edited by
 * hand, so keeping them identical to the packaged set is the correct repair.
 */
export async function copyTreeChanged(source, target) {
  if (!fs.existsSync(source)) return 0
  let copied = 0
  for (const relative of await walk(source)) {
    const from = path.join(source, ...relative.split('/'))
    const to = path.join(target, ...relative.split('/'))
    const fromStat = await fsp.stat(from)
    const toStat = await fsp.stat(to).catch(() => null)
    if (toStat !== null && toStat.size === fromStat.size) continue
    await fsp.mkdir(path.dirname(to), { recursive: true })
    await fsp.copyFile(from, to)
    copied += 1
  }
  return copied
}

/**
 * The writable directories for one package version.
 *
 * Deliberately under the DSH home and never inside the package: `node_modules` is
 * a pnpm content-addressed store (writing there would mutate the store and is
 * shared between profiles), and the database must survive an upgrade or uninstall
 * of the plugin.
 */
export async function ensureRuntime({ home, version, assets, log = () => {} }) {
  const runtimeDir = path.join(home, 'runtimes', version)
  const dataDir = path.join(home, 'data')
  const logDir = path.join(home, 'logs')
  await fsp.mkdir(runtimeDir, { recursive: true })
  await fsp.mkdir(dataDir, { recursive: true })
  await fsp.mkdir(path.join(dataDir, 'files'), { recursive: true })
  await fsp.mkdir(logDir, { recursive: true })

  // The child resolves `config/config.yaml` and `migrations/sqlite` relative to
  // its working directory, so the runtime directory must physically hold both.
  const configCopied = await copyTreeMissing(assets.config, path.join(runtimeDir, 'config'))
  const migrationsCopied = await copyTreeChanged(assets.migrations, path.join(runtimeDir, 'migrations'))
  if (configCopied > 0 || migrationsCopied > 0) {
    log(`staged ${configCopied} config file(s) and ${migrationsCopied} migration(s) into ${runtimeDir}`)
  }

  const envPath = path.join(home, ENV_FILE_NAME)
  await ensureEnvFile(envPath, { dataDir, log })

  return {
    home,
    runtimeDir,
    dataDir,
    logDir,
    envPath,
    statePath: path.join(home, STATE_FILE_NAME),
    logPath: path.join(logDir, LOG_FILE_NAME)
  }
}

// --- loopback probes ---------------------------------------------------------

/** Bind a listener to ask the OS whether one address is truly free. */
export function isPortFree(host, port) {
  return new Promise((resolve) => {
    const server = net.createServer()
    const finish = (free) => {
      server.removeAllListeners()
      try {
        server.close(() => resolve(free))
      } catch {
        resolve(free)
      }
    }
    server.once('error', () => finish(false))
    server.listen({ host, port, exclusive: true }, () => finish(true))
  })
}

/** An OS-assigned free port on `host`. */
export function freePort(host) {
  return new Promise((resolve, reject) => {
    const server = net.createServer()
    server.once('error', reject)
    server.listen({ host, port: 0, exclusive: true }, () => {
      const address = server.address()
      const port = typeof address === 'object' && address !== null ? address.port : 0
      server.close(() => (port > 0 ? resolve(port) : reject(new Error('the OS returned no port'))))
    })
  })
}

/**
 * Whether a WeKnora server answers on `host:port`.
 *
 * `/health` alone is not enough — any service can answer `{"status":"ok"}` — so the
 * SPA at `/` must also identify itself. Both checks use a short timeout because
 * this runs in a start loop and on adoption.
 */
export async function probeWeKnora(host, port, { fetchImpl = globalThis.fetch, timeoutMs = 1_500 } = {}) {
  if (typeof fetchImpl !== 'function') return false
  const base = `http://${host}:${port}`
  try {
    const health = await fetchImpl(`${base}/health`, {
      signal: AbortSignal.timeout(timeoutMs),
      headers: { accept: 'application/json' }
    })
    if (!health.ok) return false
    const payload = await health.json()
    if (payload === null || typeof payload !== 'object' || payload.status !== 'ok') return false
  } catch {
    return false
  }
  try {
    const page = await fetchImpl(`${base}/`, {
      signal: AbortSignal.timeout(timeoutMs),
      headers: { accept: 'text/html' }
    })
    if (!page.ok) return false
    const html = await page.text()
    return html.includes('WeKnora')
  } catch {
    return false
  }
}